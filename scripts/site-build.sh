#!/bin/sh
#
# site-build.sh: generate the static site in site.out/ from site.in/.
#
# Feature: prompts/features/01-site-build.md
#
# Usage: site-build.sh [DIRECTORY_INPUT] [DIRECTORY_OUTPUT]
#
# The default DIRECTORY_INPUT is site.in/ and the default DIRECTORY_OUTPUT is
# site.out/, both relative to the repository root.
# Every site.in/*.txt input file is converted to site.out/<name>.html.
# The HTML page structure lives in site.in/template.html, not in this script.
# The template marker <!-- SITE-CONTENT --> marks where page content is inserted.
#
# The dashboard page may contain __KEY__ placeholders for live state.
# Values come from the state file (dataflow.out/site-state.txt by default,
# overridable with SITE_STATE_FILE), written by scripts/site-state-fetch.sh.
# When the state file is absent, remaining placeholders render as
# "unavailable", so the build stays portable.
#
# Generated output is stamped with a generated-file marker and must not be
# edited manually.
set -eu

DIRECTORY_SCRIPT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPOSITORY_ROOT=$(CDPATH= cd -- "$DIRECTORY_SCRIPT/.." && pwd)

DIRECTORY_INPUT=${1:-"$REPOSITORY_ROOT/site.in"}
DIRECTORY_OUTPUT=${2:-"$REPOSITORY_ROOT/site.out"}
FILE_TEMPLATE="$DIRECTORY_INPUT/template.html"
COMMENT_MARKER='<!-- SITE-CONTENT -->'
FILE_STATE=${SITE_STATE_FILE:-"$REPOSITORY_ROOT/dataflow.out/site-state.txt"}

if [ ! -d "$DIRECTORY_INPUT" ]; then
    echo "site-build: input directory not found: $DIRECTORY_INPUT" >&2
    exit 1
fi

if [ ! -f "$FILE_TEMPLATE" ]; then
    echo "site-build: template not found: $FILE_TEMPLATE" >&2
    exit 1
fi

if ! grep -q "$COMMENT_MARKER" "$FILE_TEMPLATE"; then
    echo "site-build: template is missing the marker line: $COMMENT_MARKER" >&2
    exit 1
fi

# Substitute __KEY__ placeholders from the state file; any leftovers render
# as "unavailable".
substitute_state() {
    file_input=$1
    file_output=$2
    file_temporary=$(mktemp)

    cp "$file_input" "$file_temporary"

    if [ -f "$FILE_STATE" ]; then
        while IFS='=' read -r key value; do
            [ -n "$key" ] || continue
            value_escaped=$(printf '%s' "$value" | sed 's/[&\\|]/\\&/g')
            sed "s|__${key}__|${value_escaped}|g" "$file_temporary" > "$file_temporary.new"
            mv "$file_temporary.new" "$file_temporary"
        done < "$FILE_STATE"
    fi

    sed 's/__[A-Z0-9_]*__/unavailable/g' "$file_temporary" > "$file_output"
    rm -f "$file_temporary"
}

# Map a page basename to its display title.
page_title() {
    name_base=$1

    case "$name_base" in
        index)     echo "Model Render Print" ;;
        dashboard) echo "Dashboard" ;;
        frame)     echo "Assembly Frame" ;;
        rib)       echo "Rib + First Row" ;;
        *)         echo "$name_base" ;;
    esac
}

mkdir -p "$DIRECTORY_OUTPUT"

count_built=0
for file_input in "$DIRECTORY_INPUT"/*.txt; do
    if [ ! -f "$file_input" ]; then
        continue
    fi
    name_base=$(basename "$file_input" .txt)
    title_escaped=$(page_title "$name_base" | sed 's/\\/\\\\/g; s/&/\\&/g; s|/|\\/|g')
    file_output="$DIRECTORY_OUTPUT/$name_base.html"
    file_temporary=$(mktemp)
    {
        echo '<!-- generated by scripts/site-build.sh; do not edit manually -->'
        sed "s/__TITLE__/$title_escaped/g" "$FILE_TEMPLATE" | sed "/$COMMENT_MARKER/q" | sed '$d'
        sed 's/^/    /' "$file_input"
        sed -n "/$COMMENT_MARKER/,\$p" "$FILE_TEMPLATE" | sed '1d'
    } > "$file_temporary"
    substitute_state "$file_temporary" "$file_output"
    rm -f "$file_temporary"
    count_built=$((count_built + 1))
done

echo "site-build: built $count_built page(s) into $DIRECTORY_OUTPUT"

# Copy authored assets (non-.txt, non-template files) verbatim, so pages can
# reference scripts, styles, and images from site.out/.
count_assets=0
for file_asset in "$DIRECTORY_INPUT"/*; do
    if [ ! -f "$file_asset" ]; then
        continue
    fi
    name_asset=$(basename "$file_asset")
    case "$name_asset" in
        .*)                    continue ;;
        *.txt|template.html)   continue ;;
    esac
    cp "$file_asset" "$DIRECTORY_OUTPUT/$name_asset"
    count_assets=$((count_assets + 1))
done

echo "site-build: copied $count_assets asset(s) into $DIRECTORY_OUTPUT"

# Copy the generated assembly-frame model (if present) so the frame page
# can load it; it lives in dataflow.out/ (generated, not version-controlled).
FILE_FRAME_MODEL="$REPOSITORY_ROOT/dataflow.out/frame/frame-assembled.obj"
if [ -f "$FILE_FRAME_MODEL" ]; then
    cp "$FILE_FRAME_MODEL" "$DIRECTORY_OUTPUT/frame-assembled.obj"
    echo "site-build: copied the assembly-frame model"
fi

# Copy the generated rib + first-row model (if present) so the rib page
# can load it; it lives in dataflow.out/ (generated, not version-controlled).
FILE_RIB_MODEL="$REPOSITORY_ROOT/dataflow.out/rib/rib-firstrow.obj"
if [ -f "$FILE_RIB_MODEL" ]; then
    cp "$FILE_RIB_MODEL" "$DIRECTORY_OUTPUT/rib-firstrow.obj"
    echo "site-build: copied the rib + first-row model"
fi

# Copy the printable rib STL (if present) for the rib page's download link.
FILE_RIB_STL="$REPOSITORY_ROOT/dataflow.out/rib/rib.stl"
if [ -f "$FILE_RIB_STL" ]; then
    cp "$FILE_RIB_STL" "$DIRECTORY_OUTPUT/rib.stl"
    echo "site-build: copied the rib STL"
fi
exit 0
